export interface LibraryIcon {
  id: string
  name: string
  /** 256-char flat pixel string, the format PixelIcon renders. */
  data: string
}

export const ICON_LIBRARY: LibraryIcon[] = DEFS.map((d) => {
  if (d.rows.length !== 16 || d.rows.some((r) => r.length !== 16 || !/^[0-9A-F.]{16}$/.test(r))) {
    throw new Error(`iconLibrary: malformed icon "${d.id}"`)
  }
  return { id: d.id, name: d.name, data: d.rows.join('') }
})

/** Deterministic default icon for a freshly generated program. */
export function iconForName(name: string): string {
  let h = 0
  for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) >>> 0
  return ICON_LIBRARY[h % ICON_LIBRARY.length].data
}
